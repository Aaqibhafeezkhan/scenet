"""Generate the diagnostics reference: an entry for every rule and every compile note.

When `scenet check` or the compiler says something, the reader looks it up here, as in
Rust's error index. Each entry gives the id and level, what it says, why it happens, how to
fix it, the keys that can give it, the release it appeared in, a document that gives it and
the same document fixed. Everything but the documents comes from the package:

- the rules, from `scenet.diagnostics.RULES`, and the compile notes, from
  `scenet.diagnostics.COMPILE_NOTES`;
- the keys, from the language reference's cards (`scripts/build_language_pages.py`), each
  of which links back to the entries of what it can give;
- what each document gives, from checking and compiling it, as `scenet check --deep` and
  `scenet build` print it.

The documents are `tests/rule_corpus/`: a document per id, named after it, that gives that
diagnostic and nothing else, and its fixed twin in `tests/rule_corpus/fixed/`, under the
same name, that gives nothing at all. Both are read beside `examples/gallery`, as the
playground reads every document, so the pictures, fonts and puppet they name are the
gallery's. `tests/test_diagnostics_reference.py` holds every pair to that.

"Since" is the minor release that first gave the diagnostic, from
`docs/reference/diagnostics.since.toml`, which `--mine-since` writes from the release tags.
One added since the last release takes the next minor version, and the test says so.

Run from the repository root after changing a rule, a compile note, a corpus document or a
key card's diagnostics:

    uv run python scripts/build_diagnostics.py               # rewrite the page
    uv run python scripts/build_diagnostics.py --check       # exit 1 if it is stale
    uv run python scripts/build_diagnostics.py --mine-since  # rewrite since.toml from tags
"""

import argparse
import functools
import importlib.util
import re
import subprocess
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType

from scenet.diagnostics import COMPILE_NOTES, RULES, Rule

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
PAGE = DOCS / "reference" / "diagnostics.md"
SINCE = DOCS / "reference" / "diagnostics.since.toml"
CORPUS = ROOT / "tests" / "rule_corpus"
FIXED = CORPUS / "fixed"
#: The folder every document of the page is read beside, as the playground reads one.
BESIDE = "examples/gallery"
GALLERY = ROOT / BESIDE

#: The rules the cheap pass cannot find: they surface only once the solver runs.
DEEP = frozenset({"layout", "balloon-placement", "sfx-placement"})

#: A sentence each compile note has said since it was first given, to find that release by.
#: A note's name came later than most of the notes themselves, so the name cannot date it.
NOTE_SENTENCES = {
    "camera-retreated": "camera retreated to",
    "curved-tail": "needed a curved tail",
    "cropped-mouth": "mouth is outside the panel",
    "cropped-marks": "the camera makes no room for marks",
    "inset-covers-face": "an inset covers",
    "slant-cuts-face": "the slanted edge of this panel",
    "italic-stand-in": "no italic face is named",
    "bold-italic-stand-in": "no bold italic face is named",
}

GENERATED = (
    "<!-- Generated by scripts/build_diagnostics.py from scenet.diagnostics and "
    "tests/rule_corpus/. Edit those and regenerate; do not edit this file. -->"
)

#: The groups of the page, in order: each a heading, what it holds, and which ids.
GROUPS = (
    (
        "Errors",
        "A contradiction the compiler cannot build past. `scenet check` reports it and fails, "
        "and `scenet build` stops on the first it meets, exit status 1.",
        lambda name: name in RULES and RULES[name].level == "error",
    ),
    (
        "Notes from `scenet check`",
        "A house limit, or something a comic script seems to mean and does not say. The "
        "document still compiles, and a note alone never fails the check.",
        lambda name: name in RULES and RULES[name].level == "note",
    ),
    (
        "Notes from the compiler",
        "The document is valid, and compiling it decided something it did not literally ask "
        "for. `scenet build` prints each as a `note:` line, and "
        "{attr}`CompileResult.compile_notes <scenet.pipeline.CompileResult.compile_notes>` "
        "gives each with its name.",
        lambda name: name in COMPILE_NOTES,
    ),
)


def _load(name: str, path: Path) -> ModuleType:
    """Import a module that is not in a package: a script, or a documentation extension."""
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot import {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def language() -> ModuleType:
    """`scripts/build_language_pages.py`, whose cards say which keys give what."""
    return _load("build_language_pages", ROOT / "scripts" / "build_language_pages.py")


def examples() -> ModuleType:
    """The `scenet-example` directive, which says what a document gives as the build reads it."""
    return _load("scenet_examples", DOCS / "_ext" / "scenet_examples.py")


# ---------------------------------------------------------------- the catalogue


def catalogue() -> dict[str, Rule]:
    """Every diagnostic there is, by id: the rules, then the compile notes."""
    return {**RULES, **COMPILE_NOTES}


def ids() -> list[str]:
    """Every id, in the page's order: by group, then A to Z."""
    return [name for _, _, member in GROUPS for name in sorted(catalogue()) if member(name)]


# ---------------------------------------------------------------- the documents


def kind_of(path: Path) -> str:
    """What a corpus document is, by its name."""
    if path.suffix == ".script":
        return "script"
    return "scene" if path.name.endswith(".scene.yaml") else "panel"


def documents(name: str) -> list[Path]:
    """The corpus documents that give a diagnostic: `unknown-key.panel.yaml`, and so on."""
    return sorted(
        path for path in CORPUS.iterdir() if path.is_file() and path.name.split(".")[0] == name
    )


def fixed(path: Path) -> Path:
    """A corpus document's fixed twin."""
    return FIXED / path.name


def told(path: Path) -> list[str]:
    """Every diagnostic a document gives, by id, read beside the gallery."""
    text = path.read_text(encoding="utf-8")
    given: list[str] = examples().told(text, kind_of(path), GALLERY, name=path.name)
    return given


def said(path: Path) -> list[str]:
    """What the command line prints of a document that gives something, line by line.

    `scenet check` for a rule, as `file:line:column: rule: message`; `scenet build` for a
    compile note, as `note: message`, the panel's name first in a document of several.
    """
    text = path.read_text(encoding="utf-8")
    kind = kind_of(path)
    found = examples().findings(text, kind, GALLERY, name=path.name)
    if found:
        lines = []
        for item in found:
            line = item.region.start.line if item.region else 1
            column = item.region.start.column if item.region else 1
            level = "note: " if item.level == "note" else ""
            lines.append(f"{path.name}:{line}:{column}: {level}{item.rule}: {item.message}")
        return lines
    return [
        f"note: {message}" if panel is None else f"note: {panel}: {message}"
        for panel, _, message in examples().compile_notes(text, kind, GALLERY)
    ]


def command(name: str, path: Path) -> str:
    """The command that prints what the document gives."""
    if name in COMPILE_NOTES:
        return f"scenet build {path.name}"
    return f"scenet check --deep {path.name}" if name in DEEP else f"scenet check {path.name}"


# ---------------------------------------------------------------- the keys


@dataclass(frozen=True)
class Key:
    """A key card that gives a diagnostic: its name and where its card is."""

    name: str
    page: str
    anchor: str

    @property
    def link(self) -> str:
        """A link to the card, in its name."""
        return f"[`{self.name}`](language/{self.page}.md#{self.anchor})"


@functools.cache
def _given() -> dict[str, list[Key]]:
    """The cards that give each diagnostic, by id, each named on its card."""
    build = language()
    given: dict[str, list[Key]] = {}
    for name, card in sorted(build.cards().items()):
        for rule in build.diagnostics_of(card):
            given.setdefault(rule, []).append(Key(name, card.page, card.anchor))
    return given


def _keys(name: str) -> str:
    """The keys that give a diagnostic, as the Keys row says them.

    Four rules any key can give are said once, for every key, rather than listed 128 times;
    the keys that give them for a reason of their own are listed after.
    """
    build = language()
    if name in build.DOCUMENT_RULES:
        return "None: it is about the whole document, not about one key"
    cards = build.cards()
    keys = _given().get(name, [])
    own = [key for key in keys if name in build.DIAGNOSTICS.get(key.name, ())]
    every = "[every key](language/keys.md)"
    if name == "invalid-field":
        return f"Any key: each of {every} holds a value of one shape"
    if name == "missing-field":
        return "A required key: " + ", ".join(key.link for key in keys)
    if name in ("unknown-key", "duplicate-key"):
        mappings = [key for key in keys if build.holds_a_mapping(cards[key.name])]
        extra = [key for key in own if key not in mappings]
        text = "Any key that holds a mapping: " + ", ".join(key.link for key in mappings)
        return text + ("; and " + ", ".join(key.link for key in extra) if extra else "")
    if name in build.FILE_RULES.values():
        family = next(family for family, rule in build.FILE_RULES.items() if rule == name)
        page = {"puppet": "[a puppet file](language/puppet.md)"}.get(
            family, "[an artwork contract](language/artwork.md)"
        )
        text = f"Every key of {page}"
        return text + ("; and " + ", ".join(key.link for key in own) if own else "")
    return ", ".join(key.link for key in keys)


# ---------------------------------------------------------------- since


@functools.cache
def since() -> dict[str, str]:
    """`diagnostics.since.toml`: the minor release each diagnostic was first given in."""
    if not SINCE.exists():
        return {}
    found: dict[str, str] = tomllib.loads(SINCE.read_text(encoding="utf-8"))["since"]
    return found


def _git(*arguments: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(  # noqa: S603
        ["git", *arguments],  # noqa: S607
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )


def _tags() -> list[str]:
    listed = _git("tag", "--list", "v*").stdout.split()
    return sorted(listed, key=lambda tag: tuple(int(part) for part in tag[1:].split(".")))


def _rules_at(tag: str) -> set[str]:
    """The rules a release's catalogue held."""
    text = _git("show", f"{tag}:src/scenet/diagnostics.py").stdout
    return set(re.findall(r'^    "([a-z-]+)": Rule\(', text, re.MULTILINE))


def _gave_note_at(tag: str, sentence: str) -> bool:
    return _git("grep", "-q", "-F", sentence, tag, "--", "src/scenet").returncode == 0


def upcoming() -> str:
    """The next minor release, which a diagnostic added since the last one is given."""
    latest = _tags()[-1][1:].split(".")
    return f"{latest[0]}.{int(latest[1]) + 1}"


def mine() -> str:
    """`diagnostics.since.toml`, from the release tags."""
    found: dict[str, str] = {}
    for tag in _tags():
        version = ".".join(tag[1:].split(".")[:2])
        for rule in _rules_at(tag):
            found.setdefault(rule, version)
        for note, sentence in NOTE_SENTENCES.items():
            if note not in found and _gave_note_at(tag, sentence):
                found[note] = version
    for name in catalogue():
        found.setdefault(name, upcoming())
    lines = [
        "# The minor release each diagnostic was first given in: for a rule, the first release",
        "# tag whose catalogue held it; for a compile note, the first that said its sentence,",
        "# since the notes were given long before they were named. One added since the last",
        "# release takes the next minor version.",
        "#",
        "# Mined from the tags by `uv run python scripts/build_diagnostics.py --mine-since`.",
        "",
        "[since]",
        *(f'"{name}" = "{version}"' for name, version in sorted(found.items())),
    ]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- the page


def _slug(text: str) -> str:
    return re.sub(r"[^\w\- ]", "", text.strip().lower().replace(" ", "-"))


def _gallery(name: str) -> list[str]:
    """The gallery examples that give a diagnostic, as links to the gallery page."""
    entries = language().gallery()
    return [
        f"[{entry['title']}](../gallery.md#{_slug(entry['title'])})"
        for entry in entries
        if name in entry.get("notes", [])
    ]


def _example(path: Path, gives: str | None) -> str:
    options = [f":gives: {gives}"] if gives else []
    if kind_of(path) == "script":
        options.append(":kind: script")
    options.append(f":beside: {BESIDE}")
    text = path.read_text(encoding="utf-8").rstrip("\n")
    return "```{scenet-example}\n" + "\n".join(options) + "\n\n" + text + "\n```\n"


def _pair(name: str, path: Path) -> str:
    output = "\n".join(said(path))
    return (
        f"Checked as `{path.name}`:\n\n{_example(path, name)}\n"
        f"`{command(name, path)}` says:\n\n```text\n{output}\n```\n\n"
        f"Fixed:\n\n{_example(fixed(path), None)}"
    )


def entry(name: str) -> str:
    """One diagnostic's entry: its heading, its facts, why, how to fix it, and the pair."""
    rule = catalogue()[name]
    rows = [
        ("Level", rule.level),
        ("Says", rule.summary),
        ("Keys", _keys(name)),
        ("Since", since().get(name, "?")),
    ]
    shown = _gallery(name)
    if shown:
        rows.append(("In the gallery", ", ".join(shown)))
    table = "| | |\n|---|---|\n" + "\n".join(f"| {key} | {value} |" for key, value in rows)
    paths = documents(name)
    if paths:
        pairs = "\n".join(_pair(name, path) for path in paths)
    else:
        pairs = (
            "No document gives it on purpose. It is what a Scenet error with no more "
            "specific rule is reported as: a document that finds one has found a gap in this "
            "catalogue, or a bug.\n"
        )
    return (
        f"### `{name}`\n\n{table}\n\n**Why it happens.** {rule.description}\n\n"
        f"**How to fix it.** {rule.help}\n\n{pairs}"
    )


def _glance() -> str:
    rows = "\n".join(
        f"| [`{name}`](#{name}) | {catalogue()[name].level} | {catalogue()[name].summary} |"
        for name in ids()
    )
    return f"| Id | Level | Says |\n|---|---|---|\n{rows}\n"


INTRO = """\
Everything `scenet check` reports and every note the compiler gives, each with an entry: what
it says, why it happens, how to fix it, the keys that can give it and the release it was
first given in -- then a document that gives it, what the command line prints of that
document, and the same document fixed. Every document on this page is checked by the test
suite: the first of each pair gives exactly that diagnostic, and its fixed twin gives
nothing at all.

The ids are stable across releases. A report prefixes a rule's id with `scenet/`, as
`scenet/unknown-key`; SARIF links each rule here, from its `helpUri`. A compile note's name is
what a gallery example's `notes:` declares it by. The documents name pictures, fonts and a
puppet the gallery has beside it, which the playground has beside every document it opens.
"""


def page() -> str:
    """The whole page."""
    groups = "\n".join(
        f"## {heading}\n\n{what}\n\n"
        + "\n".join(entry(name) for name in sorted(catalogue()) if member(name))
        for heading, what, member in GROUPS
    )
    return f"{GENERATED}\n\n# Diagnostics\n\n{INTRO}\n## At a glance\n\n{_glance()}\n{groups}"


def stale() -> bool:
    """Whether the committed page differs from a fresh build."""
    return not PAGE.exists() or PAGE.read_text(encoding="utf-8") != page()


def main() -> int:
    """Rewrite the page, or with `--check` report whether it is stale; `--mine-since` first."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report whether it is stale")
    parser.add_argument("--mine-since", action="store_true", help="rewrite since.toml from tags")
    args = parser.parse_args()
    if args.mine_since:
        SINCE.write_text(mine(), encoding="utf-8", newline="\n")
        print(f"wrote {SINCE.relative_to(ROOT)}")
        since.cache_clear()
    if args.check:
        if stale():
            print(f"stale: {PAGE.relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    if stale():
        PAGE.write_text(page(), encoding="utf-8", newline="\n")
        print(f"wrote {PAGE.relative_to(ROOT)}")
    else:
        print("everything is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
