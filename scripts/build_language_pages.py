def _script_form(card: Card) -> str | None:
    if card.family != "document" or card.name in NOT_IN_A_SCRIPT:
        return None
    if card.name in SCRIPT_FORMS:
        return SCRIPT_FORMS[card.name]
    word = re.split(r"[.\[]", card.name, maxsplit=1)[0]
    if word in ("panel", "setting", "cast", "staging", "lettering", "palette"):
        block = card.name.split(".")[0]
        return f"`@{block}:` in a panel, or `{block}:` in the front matter"
    return None


def _where(card: Card) -> str:
    """Where the key is written: which documents, and how a comic script says it."""
    places = []
    kinds = {occurrence.kind for occurrence in card.occurrences}
    scene_paths = {o.path for o in card.occurrences if o.kind == "scene"}
    if card.family == "artwork":
        places.append("an artwork contract, the `.art.yaml` beside its picture")
    elif card.family == "puppet":
        places.append("a puppet file, a `.puppet.yaml`")
    else:
        if "panel" in kinds:
            places.append("a `.panel.yaml`")
        if any(path.startswith("panels.*.") for path in scene_paths):
            places.append("a panel under `panels:`")
        defaults = {path for path in scene_paths if not path.startswith(("panels", "page"))}
        if defaults:
            places.append("beside `panels:`, for every panel")
        if not places:
            places.append("a `.scene.yaml`")
    where = "; ".join(places)
    where = where[0].upper() + where[1:]
    form = _script_form(card)
    return f"{where}. In a comic script: {form}" if form else f"{where}. Not in a comic script"


#: The keys a script entry is written under. The schema requires the one an entry names, which
#: says only that an entry is one of the three.
VERBS = ("say", "caption", "sfx")


def _required(card: Card) -> bool:
    """Whether a document that writes the key's parent must write it.

    A scene's panel may inherit anything, so only the other documents say.
    """
    if card.name in VERBS:
        return False
    return any(o.required for o in card.occurrences if o.kind != "scene")


def _default(card: Card) -> str:
    required = _required(card)
    if required:
        return "none: required"
    node = card.node
    for branch in [node, *_branches(node)]:
        if "default" in branch:
            value = branch["default"]
            if value in ({}, [], None):
                return "none"
            if isinstance(value, dict):
                return "each key's own"
            return _value(value)
    return "none"


#: The one finding every fault in a file a document names is reported as, by its family: a
#: puppet file's at the key that is wrong, an artwork contract's at the line of the fault.
FILE_RULES = {"puppet": "puppet-file", "artwork": "artwork-contract"}


def _diagnostics(card: Card) -> str:
    if card.family in FILE_RULES:
        return f"`{FILE_RULES[card.family]}`"
    rules = ["invalid-field"]
    if _required(card):
        rules.append("missing-field")
    if any(b.get("type") == "object" or "properties" in b for b in _branches(card.node)):
        rules.extend(("unknown-key", "duplicate-key"))
    rules.extend(DIAGNOSTICS.get(card.name, ()))
    return ", ".join(f"`{rule}`" for rule in dict.fromkeys(rules))


@functools.cache
def since() -> dict[str, Any]:
    """`since.toml`: each key's release, and each value a key gained later."""
    if not SINCE.exists():
        return {"keys": {}, "values": {}}
    return tomllib.loads(SINCE.read_text(encoding="utf-8"))


def _values(card: Card) -> str:
    named = values_of(card.node)
    later = since().get("values", {})
    words = [
        f"`{name}`"
        + (f" (since {later[f'{card.name}={name}']})" if f"{card.name}={name}" in later else "")
        for name in named
    ]
    ranges = ranges_of(card.node)
    if words:
        return ", ".join(words)
    return ", ".join(ranges)


@functools.cache
def gallery() -> list[dict[str, Any]]:
    """The gallery's examples, in the manifest's order."""
    return yaml.safe_load(MANIFEST.read_text(encoding="utf-8"))["examples"]


def _slug(text: str) -> str:
    return re.sub(r"[^\w\- ]", "", text.strip().lower().replace(" ", "-"))


def gallery_of(card: Card) -> list[dict[str, Any]]:
    """The gallery examples whose `doc:` names this card."""
    doc = f"reference/language/{card.page}.md#{card.anchor}"
    return [entry for entry in gallery() if entry.get("doc") == doc]


def facts(card: Card) -> str:
    """The generated half of a card: its meaning, then a table of its facts."""
    rows = [
        ("Where", _where(card)),
        ("Type", type_of(card.node)),
    ]
    values = _values(card)
    if values:
        rows.append(("Values", values))
    rows.append(("Default", _default(card)))
    rows.append(("Since", str(since()["keys"].get(card.name, "?"))))
    rows.append(("Diagnostics", _diagnostics(card)))
    examples = gallery_of(card)
    if examples:
        links = ", ".join(
            f"[{entry['title']}](../../gallery.md#{_slug(entry['title'])})" for entry in examples
        )
        rows.append(("In the gallery", links))
    table = "| | |\n|---|---|\n" + "\n".join(f"| {key} | {value} |" for key, value in rows)
    return f"{card.description}\n\n{table}\n"


# ---------------------------------------------------------------- the pages


def pages() -> list[Path]:
    """Every page of the language reference."""
    return sorted(LANGUAGE.glob("*.md"))


def rewritten(text: str) -> str:
    """A page with every facts block regenerated. A block naming no key is left as it is."""
    known = cards()

    def fill(match: re.Match[str]) -> str:
        name = match["name"]
        if name not in known:
            return match.group(0)
        return f"<!-- facts: {name} -->\n{facts(known[name])}<!-- /facts -->"

    return FACTS.sub(fill, text)


def index_table() -> str:
    """The A-Z index: every card, its document, its meaning in a line, and since."""
    document = {"document": "panel, scene", "artwork": "artwork contract", "puppet": "puppet"}
    rows = []
    for card in sorted(cards().values(), key=lambda c: (c.name.lower().lstrip("<"), c.name)):
        kinds = {o.kind for o in card.occurrences}
        written = (
            document[card.family] if card.family != "document" or "panel" in kinds else "scene"
        )
        first = card.description
        rows.append(
            f"| [`{card.name}`]({card.page}.md#{card.anchor}) | {written} | {first} | "
            f"{since()['keys'].get(card.name, '?')} |"
        )
    return "| Key | In | What it is | Since |\n|---|---|---|---|\n" + "\n".join(rows) + "\n"


def expected() -> dict[Path, str]:
    """Every page as it should be: its facts regenerated, and the index's table."""
    found = {page: rewritten(page.read_text(encoding="utf-8")) for page in pages()}
    if INDEX in found:
        text = found[INDEX]
        start = text.index(INDEX_BEGIN) + len(INDEX_BEGIN)
        end = text.index(INDEX_END)
        found[INDEX] = f"{text[:start]}\n{index_table()}{text[end:]}"
    return found


def stale() -> list[Path]:
    """The pages that differ from a fresh build."""
    return [page for page, text in expected().items() if page.read_text(encoding="utf-8") != text]


def placed() -> dict[str, list[Path]]:
    """Each card's name, and the pages a facts block for it is on."""
    found: dict[str, list[Path]] = {}
    for page in pages():
        for match in FACTS.finditer(page.read_text(encoding="utf-8")):
            found.setdefault(match["name"], []).append(page)
    return found


# ---------------------------------------------------------------- mining the tags


def _git(*arguments: str) -> str:
    return subprocess.run(  # noqa: S603
        ["git", *arguments],  # noqa: S607
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    ).stdout


def _tags() -> list[str]:
    listed = _git("tag", "--list", "v*").split()
    return sorted(listed, key=lambda tag: tuple(int(part) for part in tag[1:].split(".")))


def _schemas_at(tag: str) -> Iterator[tuple[str, dict[str, Any]]]:
    present = _git("ls-tree", "--name-only", tag, f"{EDITOR_SCHEMAS}/").split()
    for kind in SCHEMAS:
        path = f"{EDITOR_SCHEMAS}/{kind}.schema.json"
        if path in present:
            yield kind, json.loads(_git("show", f"{tag}:{path}"))


#: Keys the frontend accepted before 0.7, when the published schema was the IR's and had no
#: word for them, by the key whose release they share: a script entry's verb is as old as
#: what it holds, and a named place as old as the masses it expands into.
CONVENIENCES = {
    "say": "say.text",
    "caption": "caption.text",
    "sfx": "sfx.text",
    "setting.place": "setting.masses",
}


def _identities(family: str, path: str, owner: str, key: str) -> tuple[str, str]:
    """How a key is matched across releases: by its path, and by the model and key it is."""
    return f"{family}:{path}", f"{family}#{owner}.{key}"


def _older(one: str, other: str) -> bool:
    return tuple(int(part) for part in one.split(".")) < tuple(
        int(part) for part in other.split(".")
    )


def _written_at(tag: str) -> dict[str, list[dict[str, Any]]]:
    """Every key the schemas at a tag let a document write, by each identity it is known by.

    By path, and by the model and key: until 0.7 the published schema was the IR's, where a
    script entry is not under its verb (`script[].by`).
    """
    written: dict[str, list[dict[str, Any]]] = {}
    for kind, schema in _schemas_at(tag):
        for occurrence in occurrences(kind, schema):
            entry = {"node": occurrence.node, "defs": schema.get("$defs", {})}
            for found in _identities(
                FAMILY[kind], occurrence.path, occurrence.owner, occurrence.key
            ):
                written.setdefault(found, []).append(entry)
    return written


def mine() -> str:
    """`since.toml`, from the schemas the editor shipped at every release tag."""
    minor = {tag: ".".join(tag[1:].split(".")[:2]) for tag in _tags()}
    latest = max(minor.values(), key=lambda v: tuple(int(p) for p in v.split(".")))
    major, number = latest.split(".")
    upcoming = f"{major}.{int(number) + 1}"
    keys: dict[str, str] = {}
    values: dict[str, str] = {}
    for tag, version in minor.items():
        written = _written_at(tag)
        for card in cards().values():
            met = [
                found
                for occurrence in card.occurrences
                for found in _identities(card.family, occurrence.path, card.owner, card.key)
                if found in written
            ]
            if not met:
                continue
            keys.setdefault(card.name, version)
            for name in _values_at(written, met):
                values.setdefault(f"{card.name}={name}", version)
    # A convenience the frontend accepted before the published schema described what people
    # write has no key of its own in that schema: it is as old as the key it stands beside.
    for name, beside in CONVENIENCES.items():
        if beside in keys and (name not in keys or _older(keys[beside], keys[name])):
            # Its names were first described when it was, which is not when they came.
            described = keys.get(name)
            for value, version in values.items():
                if value.startswith(f"{name}=") and version == described:
                    values[value] = keys[beside]
            keys[name] = keys[beside]
    for card in cards().values():
        keys.setdefault(card.name, upcoming)
        for name in values_of(card.node):
            values.setdefault(f"{card.name}={name}", upcoming)
    later = {
        key: version
        for key, version in sorted(values.items())
        if version != keys[key.split("=", 1)[0]]
    }
    lines = [
        "# The minor release each key of the language first appeared in: the first release tag",
        "# whose published JSON Schemas let a document write it. A key added since the last",
        "# release takes the next minor version. `[values]` is each name a key gained after it",
        "# was written, as `key=name`.",
        "#",
        "# Mined from the tags by `uv run python scripts/build_language_pages.py --mine-since`.",
        "",
        "[keys]",
        *(f'"{name}" = "{version}"' for name, version in sorted(keys.items())),
        "",
        "[values]",
        *(f'"{name}" = "{version}"' for name, version in later.items()),
    ]
    return "\n".join(lines) + "\n"


def _values_at(written: dict[str, list[dict[str, Any]]], met: list[str]) -> list[str]:
    """Every name the paths `met` take at a tag, resolving `$ref`s against that tag's schema."""
    names: list[str] = []

    def collect(node: object, defs: dict[str, Any], seen: frozenset[str]) -> None:
        if not isinstance(node, dict):
            return
        if "$ref" in node:
            name = node["$ref"].rsplit("/", 1)[1]
            if name not in seen and name in defs:
                collect(defs[name], defs, seen | {name})
        if "enum" in node:
            names.extend(str(value) for value in node["enum"])
        if "const" in node:
            names.append(str(node["const"]))
        for combinator in ("anyOf", "oneOf"):
            for branch in node.get(combinator, []):
                collect(branch, defs, seen)
        if isinstance(node.get("items"), dict):
            collect(node["items"], defs, seen)

    for key in met:
        for entry in written[key]:
            collect(entry["node"], entry["defs"], frozenset())
    return names


def main() -> int:
    """Rewrite the pages, or with `--check` report which are stale; `--mine-since` first."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report stale pages")
    parser.add_argument("--mine-since", action="store_true", help="rewrite since.toml from tags")
    args = parser.parse_args()
    if args.mine_since:
        SINCE.write_text(mine(), encoding="utf-8", newline="\n")
        print(f"wrote {SINCE.relative_to(ROOT)}")
        since.cache_clear()
    found = stale()
    if args.check:
        for page in found:
            print(f"stale: {page.relative_to(ROOT)}", file=sys.stderr)
        return 1 if found else 0
    for page, text in expected().items():
        if page in found:
            page.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {page.relative_to(ROOT)}")
    if not found:
        print("everything is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
