@dataclass(frozen=True)
class Occurrence:
    """One place a schema lets a key be written: its path, and the model that owns it."""

    kind: str
    path: str
    owner: str
    key: str
    node: dict[str, Any] = field(compare=False, hash=False)
    required: bool = False


def occurrences(kind: str, schema: dict[str, Any]) -> list[Occurrence]:
    """Every key a schema lets a document write, at every path it can be written at.

    A path is written as the YAML is: `camera.shot`, `cast.*.pose` under a name the author
    chooses, `script[].say.by` inside a list's entry. Each `$ref` is followed once per path.
    """
    found: list[Occurrence] = []

    def walk(node: object, path: str, owner: str, seen: frozenset[str]) -> None:
        if not isinstance(node, dict):
            return
        if "$ref" in node:
            name = node["$ref"].rsplit("/", 1)[1]
            if name not in seen:
                walk(schema["$defs"][name], path, name.removeprefix("Partial"), seen | {name})
        for combinator in ("anyOf", "oneOf", "allOf"):
            for branch in node.get(combinator, []):
                walk(branch, path, owner, seen)
        if isinstance(node.get("items"), dict):
            walk(node["items"], f"{path}[]", owner, seen)
        inner = node.get("additionalProperties")
        if isinstance(inner, dict):
            # A scene's panel holds a panel's keys, and `over`.
            child_owner = "Panel" if (kind, path) == ("scene", "panels") else owner
            walk(inner, f"{path}.*", child_owner, seen)
        required = set(node.get("required", []))
        for key, value in node.get("properties", {}).items():
            child = f"{path}.{key}" if path else key
            key_owner = owner
            if kind == "scene" and not path and key not in SCENE_KEYS:
                key_owner = "Panel"
            if isinstance(value, dict):
                found.append(Occurrence(kind, child, key_owner, key, value, key in required))
            walk(value, child, key_owner, seen)

    walk(schema, "", ROOT_OWNER[kind], frozenset())
    return found


def _placeholders(path: str) -> str:
    """`cast.*.pose` as a reader is told to write it: `cast.<id>.pose`."""
    parts = path.split(".")
    for index, part in enumerate(parts):
        if part == "*":
            parts[index] = PLACEHOLDER[parts[index - 1].removesuffix("[]")]
    return ".".join(parts)


@dataclass
class Card:
    """One key of the language, and every place it can be written."""

    name: str
    family: str
    owner: str
    key: str
    occurrences: list[Occurrence]

    @property
    def page(self) -> str:
        """The page of `docs/reference/language/` the card is on."""
        if self.family in PAGE_OF_FAMILY:
            return PAGE_OF_FAMILY[self.family]
        if self.name in ("panels", "over"):
            return "scene"
        word = re.split(r"[.\[]", self.name, maxsplit=1)[0]
        return PAGE_OF_WORD.get(word, "page" if word == "panels" else word)

    @property
    def anchor(self) -> str:
        """Its heading's anchor, as MyST and GitHub make it from `` `name` ``."""
        return re.sub(r"[^\w\- ]", "", self.name.lower().replace(" ", "-"))

    @property
    def paths(self) -> set[str]:
        """Every path it can be written at, in every schema."""
        return {occurrence.path for occurrence in self.occurrences}

    @property
    def node(self) -> dict[str, Any]:
        """Its definition: in the panel schema where it is written there, as the editor has it."""
        ranked = sorted(self.occurrences, key=lambda o: (o.kind != "panel", len(o.path)))
        return ranked[0].node

    @property
    def description(self) -> str:
        """Its meaning in one paragraph: the schema's, which an editor shows on hover."""
        return str(self.node.get("description", "")).strip()


def _name(occurrence: Occurrence) -> str:
    owner, key = MERGED.get((occurrence.owner, occurrence.key), (occurrence.owner, occurrence.key))
    if owner in PREFIX:
        return f"{PREFIX[owner]}.{key}"
    path = occurrence.path
    if occurrence.kind == "scene" and path.startswith("panels.*."):
        path = path.removeprefix("panels.*.")
    return _placeholders(path.removeprefix("script[]."))


@functools.cache
def schemas() -> dict[str, dict[str, Any]]:
    """The four published schemas, made once."""
    return {kind: make() for kind, make in SCHEMAS.items()}


@functools.cache
def cards() -> dict[str, Card]:
    """Every card, by name, from every key the four schemas define."""
    found: dict[str, Card] = {}
    for kind, schema in schemas().items():
        for occurrence in occurrences(kind, schema):
            owner, key = MERGED.get(
                (occurrence.owner, occurrence.key), (occurrence.owner, occurrence.key)
            )
            identity = (FAMILY[kind], owner, key)
            for card in found.values():
                if (card.family, card.owner, card.key) == identity:
                    card.occurrences.append(occurrence)
                    break
            else:
                name = _name(occurrence)
                if name in found:
                    raise ValueError(f"two keys would share the card {name}")
                found[name] = Card(name, FAMILY[kind], owner, key, [occurrence])
    # A card is named for its shortest path, wherever that was met first.
    renamed: dict[str, Card] = {}
    for card in found.values():
        best = min(card.occurrences, key=lambda o: (o.kind != "panel", len(o.path), o.path))
        card.name = _name(best)
        renamed[card.name] = card
    return dict(sorted(renamed.items()))


# ---------------------------------------------------------------- describing a schema node


def _branches(node: dict[str, Any]) -> list[dict[str, Any]]:
    """The non-null alternatives a node allows, with every `$ref` resolved."""
    if "$ref" in node:
        definitions = {
            name: d for schema in schemas().values() for name, d in schema.get("$defs", {}).items()
        }
        name = node["$ref"].rsplit("/", 1)[1]
        merged = {**definitions[name], **{k: v for k, v in node.items() if k != "$ref"}}
        return _branches(merged)
    for combinator in ("anyOf", "oneOf"):
        if combinator in node:
            return [
                branch
                for alternative in node[combinator]
                for branch in _branches(alternative)
                if branch.get("type") != "null"
            ]
    return [] if node.get("type") == "null" else [node]


def _number(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else str(value)


def _value(value: object) -> str:
    """A default, as YAML writes it."""
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, int | float):
        return f"`{_number(value)}`"
    if isinstance(value, str):
        return f"`{value}`"
    if isinstance(value, list) and all(isinstance(item, int | float) for item in value):
        return "`[" + ", ".join(_number(item) for item in value) + "]`"
    return f"`{json.dumps(value)}`"


def _range(node: dict[str, Any]) -> str:
    low = node.get("minimum")
    high = node.get("maximum")
    above = node.get("exclusiveMinimum")
    if low is not None and high is not None:
        return f"{_number(low)} to {_number(high)}"
    if above is not None and node.get("maximum") is not None:
        return f"above {_number(above)}, at most {_number(node['maximum'])}"
    if above is not None:
        return f"above {_number(above)}"
    if low is not None:
        return f"{_number(low)} or more"
    return ""


#: How a list names what each of its entries is, by what one entry is.
PLURAL = {
    "a name": "names",
    "text": "text",
    "a mapping": "mappings",
    "a number": "numbers",
    "a whole number": "whole numbers",
}


def _kinds(node: dict[str, Any]) -> list[str]:
    """What a node may hold, one phrase per alternative: `text`, `a name`, `a mapping`."""
    words = []
    for branch in _branches(node):
        kind = branch.get("type")
        if "const" in branch and not isinstance(branch["const"], str):
            words.append(f"`{_number(branch['const'])}`")
        elif "enum" in branch or "const" in branch:
            words.append("a name")
        elif kind == "array" and "prefixItems" in branch:
            words.append(f"`[{', '.join('number' for _ in branch['prefixItems'])}]`")
        elif kind == "array":
            items = _kinds(branch.get("items", {}))
            if len(items) == 1:
                words.append(f"a list of {PLURAL.get(items[0], items[0])}")
            else:
                words.append(f"a list, each {' or '.join(items)}")
        elif kind == "object" or "properties" in branch:
            words.append("a mapping")
        elif kind in ("number", "integer"):
            words.append("a number" if kind == "number" else "a whole number")
        elif kind == "boolean":
            words.append("`true` or `false`")
        elif kind == "string":
            words.append("text")
    return list(dict.fromkeys(words))


def type_of(node: dict[str, Any]) -> str:
    """What a key holds, in words: `text`, `a number`, `a name`, `a list of mappings`."""
    words = _kinds(node)
    return ", or ".join(words) if words else "anything"


def values_of(node: dict[str, Any]) -> list[str]:
    """Every name a key may take, in the schema's order."""
    names: list[str] = []
    for branch in _branches(node):
        if "enum" in branch:
            names.extend(str(value) for value in branch["enum"])
        elif "const" in branch:
            names.append(str(branch["const"]))
        elif branch.get("type") == "array" and isinstance(branch.get("items"), dict):
            names.extend(values_of(branch["items"]))
    return list(dict.fromkeys(names))


def ranges_of(node: dict[str, Any]) -> list[str]:
    """The range a number may take, `-45 to 45`, for each numeric alternative of a node."""
    found = []
    for branch in _branches(node):
        if branch.get("type") in ("number", "integer") and _range(branch):
            found.append(_range(branch))
        if branch.get("type") == "array" and isinstance(branch.get("items"), dict):
            found.extend(ranges_of(branch["items"]))
    return list(dict.fromkeys(found))


