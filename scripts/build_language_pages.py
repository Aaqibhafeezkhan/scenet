"""Generate the facts of every key card in the language reference, and its A-Z index.

Every key a document can write -- in a panel, a scene, an artwork contract or a puppet file --
has one card in `docs/reference/language/`: where it is written, its type, its values, its
default, the release it appeared in, the findings it can give, and the gallery examples that
show it. Those facts come from the published JSON Schemas, which are made from the
compiler's own models, and are written here between two markers in the page:

    <!-- facts: camera.shot -->
    ...generated...
    <!-- /facts -->

What comes after the end marker -- what the key means beyond its one line, how it resolves
against everything else, its limits, a document that shows it -- is written by hand. The
cards are where the pages put them; this writes inside each card, and the index, and nothing
else. `docs/reference/language/keys.md` is the A-Z index of every card, between markers too.

"Since" is the minor release whose schemas first held the key, from
`docs/reference/language/since.toml`, which `--mine-since` writes from the release tags. A key
added since the last release takes the next minor version, and the test says so.

Run from the repository root after changing a model, a schema or `since.toml`:

    uv run python scripts/build_language_pages.py               # rewrite the facts
    uv run python scripts/build_language_pages.py --check       # exit 1 if any is stale
    uv run python scripts/build_language_pages.py --mine-since  # rewrite since.toml from tags
"""

