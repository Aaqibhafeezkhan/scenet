def _preamble() -> str:
    puppets = ", ".join(f"`{name}`" for name in default_library().names())
    contents = "\n".join(f"- `{name}` — {description}" for name, description in SPEC_PARTS.items())
    return f"""\
# Scenet specification pack

Everything needed to write a Scenet panel, in one file. Published at
<{SITE}/scenet-spec.md> and regenerated from the project's own sources on every build,
so it describes the language the compiler actually accepts.

> This project is deliberately AI-generated: the compiler, its documentation and this
> file are almost entirely written by AI under human direction and review. Treat it as
> an experiment first and a tool second.

## What Scenet is

Scenet compiles a *semantic* description of a comic panel — who is in it, how they
relate, what they say — into SVG. It is a deterministic compiler built on constraint
solving and geometry. **No generative image model is involved.** The same document
always produces the same picture, byte for byte.

You describe the panel; the compiler decides every coordinate. **Never write
coordinates**, pixel positions for figures, or balloon placements: the language has
nowhere to put them, and unknown keys are rejected.

## Two ways to write a panel

1. **YAML** — `*.panel.yaml` for one panel, `*.scene.yaml` for a sequence. The whole
   language; see the `language` part.
2. **Comic script** — `*.script`. The format comic writers already use: `PANEL 1`,
   `@shot:`, a character cue, the dialogue under it, with a short YAML front matter
   declaring the cast. Dark Horse's published layout is read as written, and so are
   French scripts; each PAGE heading is a page. See the `comic-script` part.

**If you cannot run code** — a chat app, NotebookLM — write a comic script. It is the
closest thing to what you would write anyway, and the person you are helping compiles
it with one command: `scenet build panel.script`.

## The loop

1. Write the document.
2. Run `scenet check FILE`. It reports every fault at once, each with a rule id such as
   `{RULE_NAMESPACE}/unknown-actor`, a line and column, and what to do about it. Add
   `--format sarif` for a machine-readable report.
3. Fix what it reports and check again, until it prints `ok`.
4. Run `scenet build FILE` to write the SVG.

With the Scenet MCP server connected, the `validate`, `compile` and `render` tools do
the same without a shell.

**A schema-valid document is not yet a valid one.** No JSON Schema can catch the faults
that matter most — an actor id that is not in `cast`, a `left_of` ordering that loops —
so always check.

## The mistakes generators make most

- **Every actor id used in `staging` or `script` must be a key of `cast`.** Ids are
  case-sensitive.
- **`reference` names a puppet in the library, or a puppet file of the document's own by
  its path, `reference: puppets/pip.puppet.yaml`.** The shipped puppets are {puppets}.
  `pose` and `expression` must be names that puppet declares; see the `characters`
  part. Do not invent them.
- **Say who stands left of whom.** `a left_of b` in `staging` fixes it. Where staging
  says nothing, figures stand in the order of their `at:` anchors, and two at the same
  anchor by actor id, in code-point order: the same on every run, but seldom what was
  meant. State the order. There is no unordered "beside".
- **Script order is reading order.** A balloon may never sit above-and-left of the one
  before it (above-and-right in a manga, `direction: rtl`), so write the lines in the order
  they are read.
- **Shots are named** — `medium_shot`, `close_up` — never a percentage of the panel.
- **Prose in a comic script is kept and never interpreted.** Staging that matters goes
  in the front matter.

## Contents

{contents}
"""


