        "| Puppet | Heads tall | Poses | Expressions |\n"
        "|---|---|---|---|\n" + "\n".join(rows) + "\n\n"
        "One puppet may appear several times in a panel under different actor ids.\n\n"
        "## A puppet of your own\n\n"
