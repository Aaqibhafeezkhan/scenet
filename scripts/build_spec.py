def gallery_groups() -> list[tuple[str, list[dict[str, Any]]]]:
    """The gallery as the playground's menu offers it: by group, the opening example first.

    Each group in the order `groups:` names them, holding its entries in the manifest's order
    with `start:` first, as `grouped()` in `playground/src/gallery.ts` orders them.
    """
    manifest = _manifest()
    groups: list[tuple[str, list[dict[str, Any]]]] = []
    for name in manifest["groups"]:
        members = [entry for entry in manifest["examples"] if entry["group"] == name]
        members.sort(key=lambda entry: entry["file"] != manifest.get("start"))
        groups.append((name, members))
    return groups


def pictures_of(entry: dict[str, Any]) -> list[Path]:
    """An example's pictures, as `update_golden.py` keeps them: its pages, strip or panel."""
    stem = entry["file"].split(".", maxsplit=1)[0]
    return sorted(
        path for path in PICTURES.iterdir() if path.name.split(".", maxsplit=1)[0] == stem
    )


def _alt(picture: Path) -> str:
    """A picture's alternative text: what its SVG says to a screen reader, every title in order."""
    svg = picture.read_text(encoding="utf-8")
    spoken = " ".join(
        html.unescape(title) for title in re.findall(r"<title>(.*?)</title>", svg, re.S)
    )
    return MARKUP.sub(r"\\\1", spoken)


def _gallery_entry(entry: dict[str, Any]) -> str:
    path = GALLERY / entry["file"]
    # The editor extension's language id for a comic script, which the tests compile.
    language = "scenet-script" if path.suffix == ".script" else "yaml"
    images = "\n".join(
        f"![{_alt(picture)}]({picture.relative_to(DOCS).as_posix()})"
        for picture in pictures_of(entry)
    )
    link = f"{PLAYGROUND}#{urlencode({'example': entry['file']})}"
    return (
        f"### {entry['title']}\n\n{entry['summary']}\n\n{images}\n\n"
        f"[Open in the playground]({link}) · [Read about it]({entry['doc']})\n\n"
        "<details>\n<summary>Source</summary>\n\n"
        f"{_fence(path.read_text(encoding='utf-8'), language)}\n</details>\n"
    )


#: The author's tour (#321): a chapter per gallery group, in the same order.
TUTORIAL = DOCS / "tutorial"


def tour_chapters() -> list[tuple[str, str]]:
    """The tour's chapters, as its table of contents lists them: each one's file and title."""
    index = (TUTORIAL / "index.md").read_text(encoding="utf-8")
    toctree = re.search(r"```\{toctree\}\n(.*?)```", index, re.S)
    if toctree is None:
        message = f"{TUTORIAL / 'index.md'} has no table of contents"
        raise ValueError(message)
    chapters = []
    for line in toctree.group(1).splitlines():
        name = line.strip()
        if not name or name.startswith(":"):
            continue
        text = (TUTORIAL / f"{name}.md").read_text(encoding="utf-8")
        title = re.search(r"^# (.+)$", text, re.M)
        if title is None:
            message = f"{name}.md has no title"
            raise ValueError(message)
        chapters.append((f"{name}.md", title.group(1).strip()))
    return chapters


def _chapter_line(group: str) -> str:
    """The sentence that sends a group's reader to the tour's chapter on it."""
    for file, title in tour_chapters():
        if title.startswith(group):
            return f"Learn it in the tour: [{title}](tutorial/{file}).\n\n"
    return ""


def gallery_page() -> str:
    """The documentation's Gallery page, `docs/gallery.md`."""
    groups = "\n".join(
        f"## {name}\n\n{_chapter_line(name)}"
        + "\n".join(_gallery_entry(entry) for entry in members)
        for name, members in gallery_groups()
    )
    notice = GENERATED_NOTICE.format(source="examples/gallery/ and docs/images/gallery/")
    return f"{notice}# Gallery\n\n{GALLERY_INTRO}\n{groups}"


def parts(site: str = SITE) -> dict[str, str]:
    """Every part of the pack, in order, each ending in exactly one newline.

    Args:
        site: The version of the site the pack links: the root, which serves the latest
            release, or one version's own, `<root>/dev` or `<root>/v0.12`.
    """
    built = {
        "preamble": _preamble(),
        "language": _language(),
        **{
            name: _plain_captions(
                _absolute_links(
                    _plain_directives((DOCS / page).read_text(encoding="utf-8"), page), page
                )
            )
            for name, page in DOCUMENT_PARTS.items()
        },
        "characters": _characters(),
        "diagnostics": _diagnostics(),
        "schema": _schema(),
        "gallery": _gallery(),
    }
    # Every part is built linking the root, as the committed copies do -- and so does what the
    # package itself says, such as a rule's help. A version's own copy names that version
    # instead, wherever a link is.
    return {
        name: built[name].replace(f"{SITE}/", f"{site}/").rstrip("\n") + "\n" for name in SPEC_PARTS
    }


def spec_pack(site: str = SITE) -> str:
    """The whole spec pack, as committed and as published."""
    body = "\n".join(f"{MARKER.format(name=name)}\n{text}" for name, text in parts(site).items())
    return GENERATED_NOTICE.format(source="docs/, examples/gallery/ and the package") + body


def llms_txt(site: str = SITE) -> str:
    """An index of the documentation, in the shape https://llmstxt.org proposes.

    Args:
        site: The version of the site it links, as for :func:`parts`.

    Returns:
        The file's text.
    """

    def links(pages: dict[str, str]) -> str:
        return "\n".join(
            f"- [{_title(page)}]({site}/{page}.html): {note}" for page, note in pages.items()
        )

    schemas = "\n".join(
        f"- [{name.capitalize()} JSON Schema]({site}/schemas/{name}.schema.json): {what}"
        for name, what in SCHEMAS.items()
    )

    return f"""\
# Scenet

> A compiler that turns a semantic description of a comic panel — who is in it, how
> they relate, what they say — into SVG. Deterministic constraint solving and
> geometry; no generative image model is involved.

This file follows llms.txt, a community convention with no standards body behind it;
it is a distribution format, not a protocol. The project is deliberately AI-generated.
To write a panel, read the spec pack: it holds the language, the comic-script format,
the characters, the diagnostics, the JSON Schema and every example in one file.

## Specification

- [Spec pack]({site}/scenet-spec.md): everything needed to write a panel, in one file
{schemas}

## Documentation

{links(LLMS_DOCUMENTS)}

## Optional

{links(LLMS_OPTIONAL)}
- [Playground]({site}/playground/): the compiler running in a browser
- [Source](https://github.com/creatoan/scenet): the repository
"""


def skill_files() -> dict[Path, bytes]:
    """The generated half of the skill folder. `SKILL.md` itself is written by hand."""
    built = parts()
    sources = {
        "language": f"docs/{LANGUAGE}/",
        **{name: f"docs/{page}" for name, page in DOCUMENT_PARTS.items()},
        "characters": "the shipped puppet library",
        "diagnostics": f"docs/{DIAGNOSTICS_PAGE}",
    }
    files: dict[Path, bytes] = {
        SKILL / "references" / f"{name}.md": (
            GENERATED_NOTICE.format(source=sources[name]) + built[name]
        ).encode("utf-8")
        for name in SKILL_REFERENCES
    }
    gallery = SKILL / "assets" / "gallery"
    files[gallery / "manifest.yaml"] = (GALLERY / "manifest.yaml").read_bytes()
    for entry in _gallery_entries():
        files[gallery / entry["file"]] = (GALLERY / entry["file"]).read_bytes()
        # A picture travels with the example that names it, so the skill's copy compiles.
        for name in _named_files(entry):
            files[gallery / name] = (GALLERY / name).read_bytes()
    return files


def committed_files() -> dict[Path, bytes]:
    """Every generated file that lives in the repository, with its expected content."""
    return {
        PACKAGED: spec_pack().encode("utf-8"),
        GALLERY_PAGE: gallery_page().encode("utf-8"),
        **skill_files(),
    }


def write_site_files(site: Path, base: str = SITE) -> None:
    """Write the two files only the published site carries.

    Args:
        site: The assembled site directory; both files land at its root.
        base: The address that version of the site is served at, which both files link:
            `<root>/dev` for main, `<root>/v0.12` for a release. The committed copies link
            the root, which serves the latest release.
    """
    site.mkdir(parents=True, exist_ok=True)
    (site / "scenet-spec.md").write_text(spec_pack(base), encoding="utf-8", newline="\n")
    (site / "llms.txt").write_text(llms_txt(base), encoding="utf-8", newline="\n")


def _stale() -> list[Path]:
    expected = committed_files()
    stale = [
        path
        for path, content in expected.items()
        if not path.exists() or path.read_bytes() != content
    ]
    for directory in GENERATED_DIRECTORIES:
        if directory.exists():
            stale.extend(
                path
                for path in sorted(directory.rglob("*"))
                if path.is_file() and path not in expected
            )
    return stale


def main() -> int:
    """Rewrite the committed copies, or with `--check` report whether any is stale."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="report stale files instead of rewriting them"
    )
    args = parser.parse_args()

    stale = _stale()
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0

    expected = committed_files()
    for path in stale:
        if path in expected:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected[path])
            print(f"wrote {path.relative_to(ROOT)}")
        else:
            path.unlink()
            print(f"removed {path.relative_to(ROOT)}")
    if not stale:
        print("everything is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
