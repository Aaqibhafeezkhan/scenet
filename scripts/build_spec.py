LINK = re.compile(r"\]\(([^)\s]+)\)")


def _absolute_links(text: str, page: str) -> str:
    """Rewrite every relative link in a documentation page to its published URL.

    Args:
        text: The page's Markdown.
        page: Its path under `docs/`, such as `reference/language.md`.

    Returns:
        The same Markdown, with `shot_types.md#x` become `<site>/reference/shot_types.html#x`.
        Links with a scheme, and same-page anchors, are left alone: an anchor still
        resolves inside the pack, because the heading it names is in there too.
    """

    def rewrite(match: re.Match[str]) -> str:
        target = match.group(1)
        if re.match(r"[a-z][a-z0-9+.-]*:|#", target):
            return match.group(0)
        path, _, anchor = target.partition("#")
        resolved = posixpath.normpath(posixpath.join(posixpath.dirname(page), path))
        if resolved.endswith(".md"):
            resolved = resolved.removesuffix(".md") + ".html"
        return f"]({SITE}/{resolved}{'#' + anchor if anchor else ''})"

    return LINK.sub(rewrite, text)


#: A key card's example, ```` ```{scenet-example} ````, its option lines and the document.
EXAMPLE = re.compile(
    r"^(?P<ticks>`{3,})\{scenet-example\}\n(?P<options>(?::[\w-]+:.*\n)*)(?: *\n)?",
    re.MULTILINE,
)

#: A file a page includes, ```` ```{literalinclude} path ```` and its option lines.
INCLUDE = re.compile(
    r"^(?P<ticks>`{3,})\{literalinclude\} (?P<path>\S+)\n"
    r"(?P<options>(?::[\w-]+:.*\n)*)(?P=ticks)\n",
    re.MULTILINE,
)

#: A glossary term, ``{term}`text` `` or ``{term}`text <target>` ``: its text is what reads.
TERM = re.compile(r"\{term\}`(?P<text>[^`<]+?)(?:\s*<[^>]+>)?`")

#: A cross-reference to the Python API, ``{attr}`text <target>` ``: its text, as code.
PYTHON_ROLE = re.compile(
    r"\{(?:attr|class|data|exc|func|meth|mod)\}`(?P<text>[^`<]+?)(?:\s*<[^>]+>)?`"
)


def _options(lines: str) -> dict[str, str]:
    return dict(re.findall(r"^:([\w-]+):\s*(.*)$", lines, re.MULTILINE))


def _plain_directives(text: str, page: str) -> str:
    """Write a page's MyST as the Markdown it stands for, for a reader that knows no MyST.

    A key card's example is the document it shows, in a plain fence; a file the page includes
    is printed, under its caption; a glossary term is its text.
    """

    def example(match: re.Match[str]) -> str:
        kind = _options(match["options"]).get("kind")
        return f"{match['ticks']}{'text' if kind == 'script' else 'yaml'}\n"

    def include(match: re.Match[str]) -> str:
        options = _options(match["options"])
        path = posixpath.normpath(posixpath.join(posixpath.dirname(page), match["path"]))
        content = (DOCS / path).read_text(encoding="utf-8")
        caption = f"*{options['caption']}:*\n\n" if "caption" in options else ""
        return caption + _fence(content, options.get("language", "text"))

    text = INCLUDE.sub(include, EXAMPLE.sub(example, text))
    text = PYTHON_ROLE.sub(lambda match: f"`{match['text']}`", text)
    return TERM.sub(lambda match: match["text"], text)


#: A MyST code block with a caption, ```` ```{code-block} yaml ```` and `:caption: ...`.
CAPTIONED = re.compile(
    r"^(?P<indent> *)(?P<ticks>`{3,})\{code-block\} (?P<language>\S+)\n"
    r"(?P=indent):caption: (?P<caption>.+)\n(?: *\n)?",
    re.MULTILINE,
)


def _plain_captions(text: str) -> str:
    """Write each captioned code block as plain Markdown: the caption, then a plain fence.

    The pack is read as Markdown, by models and by GitHub, neither of which knows MyST's
    directives. A caption says what a block is -- `Part of story.scene.yaml` (#317) -- so it
    is kept, as a line of its own above the block.
    """

    def plain(match: re.Match[str]) -> str:
        indent = match["indent"]
        return f"{indent}*{match['caption']}:*\n\n{indent}{match['ticks']}{match['language']}\n"

    return CAPTIONED.sub(plain, text)


def language_pages() -> list[str]:
    """The language reference's pages, by path under `docs/`: the overview, then its contents."""
    index = (DOCS / LANGUAGE / "index.md").read_text(encoding="utf-8")
    toctree = TOCTREE.search(index)
    if toctree is None:
        raise ValueError(f"docs/{LANGUAGE}/index.md has no table of contents")
    entries = [
        line.strip()
        for line in toctree.group(1).splitlines()
        if line.strip() and not line.startswith(":")
    ]
    return [f"{LANGUAGE}/index.md", *(f"{LANGUAGE}/{entry}.md" for entry in entries)]


#: The opening of a fenced block, inside which a `#` line is not a heading.
_FENCE = re.compile(r"\s*(`{3,}|~{3,})")

#: A page's table of contents, a MyST directive, and the entries it lists.
TOCTREE = re.compile(r"```\{toctree\}\n(.*?)```\n?", re.DOTALL)


def _demoted(text: str) -> str:
    """A page with every heading one level deeper, its title become a section of the part."""
    lines = []
    fence = ""
    for line in text.splitlines(keepends=True):
        if fence:
            if re.fullmatch(rf"\s*{re.escape(fence[0])}{{{len(fence)},}}\s*", line):
                fence = ""
        elif (opening := _FENCE.match(line)) is not None:
            fence = opening.group(1)
        elif line.startswith("#"):
            lines.append("#" + line)
            continue
        lines.append(line)
    return "".join(lines)


def _within_the_part(text: str, page: str, titles: dict[str, str]) -> str:
    """Point a link to another page of the language reference at its heading in the part.

    The pages are one part of the pack, so `camera.md#camera` is a heading a few screens
    down, not a page of the site; a link to a page alone goes to its title.
    """

    def rewrite(match: re.Match[str]) -> str:
        target = match.group(1)
        if re.match(r"[a-z][a-z0-9+.-]*:|#", target):
            return match.group(0)
        path, _, anchor = target.partition("#")
        resolved = posixpath.normpath(posixpath.join(posixpath.dirname(page), path))
        if resolved not in titles:
            return match.group(0)
        return f"](#{anchor or titles[resolved]})"

    return LINK.sub(rewrite, text)


#: Pages of the language reference the pack leaves out: the A-Z index repeats, one line each,
#: what every card in the part already says.
NOT_IN_THE_PACK = ("reference/language/keys.md",)


def _language() -> str:
    """The `language` part: every page of the language reference, in its own order."""
    pages = [page for page in language_pages() if page not in NOT_IN_THE_PACK]
    texts = {page: (DOCS / page).read_text(encoding="utf-8") for page in pages}
    titles = {
        page: _slug(next(line for line in text.splitlines() if line.startswith("# "))[2:])
        for page, text in texts.items()
    }
    joined = []
    for page in pages:
        text = _plain_directives(texts[page], page)
        text = _absolute_links(_within_the_part(text, page, titles), page)
        # The overview's toctree lists the pages that follow it, which is what the part does.
        text = TOCTREE.sub("", text)
        joined.append(text if page.endswith("/index.md") else _demoted(text))
    return _plain_captions("\n".join(part.rstrip("\n") + "\n" for part in joined))


def _slug(heading: str) -> str:
    """A heading's anchor, as MyST and GitHub make it."""
    return re.sub(r"[^\w\- ]", "", heading.strip().lower().replace(" ", "-"))


def _title(page: str) -> str:
    """The first top-level heading of a documentation page."""
    for line in (DOCS / f"{page}.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line.removeprefix("# ").strip()
    raise ValueError(f"docs/{page}.md has no top-level heading")


def _fence(content: str, language: str) -> str:
    """A fenced block long enough that nothing inside it can close it early."""
    longest = max((len(run) for run in re.findall(r"`{3,}", content)), default=2)
    ticks = "`" * (longest + 1)
    return f"{ticks}{language}\n{content.rstrip()}\n{ticks}\n"


