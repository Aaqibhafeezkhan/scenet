"""Generate the Python reference's pages: one per public name, and the index that lists them.

Every name in `scenet.__all__` gets an entry, as a Qt class page or a cppreference function
page has one: a header card -- the import line, the module that defines it with a link to
its source, what to install, the release it appeared in, how stable it is -- and then its
signature and docstring, rendered by autodoc. A function and a main class have a page of
their own. Enumerations are grouped, one page for each group of `__all__`, and so are the
errors, on one page in the order of their hierarchy.

    docs/reference/api/public/      a page per name, or per group of small ones
    docs/reference/api/index.md     its "At a glance" table, between two markers

Both are committed, as every page of the documentation is Markdown that GitHub renders.
The groups are `__all__`'s own -- the `# -- compiling --` comments in
`src/scenet/__init__.py` -- so the overview cannot drift from what is exported.

"Since" is the minor release whose `__all__` first named it, from
`docs/reference/api/since.toml`, which `--mine-since` wrote from the release tags. A name
added since the last release takes the next minor version, and the test says so. So does a
parameter a function gained after it was public, which its page marks with
`versionadded`.

Run from the repository root after changing `__all__` or `since.toml`:

    uv run python scripts/build_api_pages.py           # rewrite the pages
    uv run python scripts/build_api_pages.py --check   # exit 1 if any is stale
"""

import argparse
import ast
import enum
import functools
import inspect
import re
import shutil
import subprocess
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

import scenet
import scenet.core

ROOT = Path(__file__).resolve().parent.parent
API = ROOT / "docs" / "reference" / "api"
PUBLIC = API / "public"
INDEX = API / "index.md"
SINCE = API / "since.toml"
INIT = ROOT / "src" / "scenet" / "__init__.py"

#: Where the package's source is read on GitHub. The built site points each link at the
#: release it documents instead (`docs/conf.py`); the Markdown, which GitHub renders, at main.
SOURCE = "https://github.com/creatoan/scenet/blob/main/src/"

#: The two markers in `index.md` between which this script writes.
BEGIN = "<!-- begin: generated by scripts/build_api_pages.py; do not edit -->"
END = "<!-- end: generated -->"

#: Every public name installs with the package itself. A name that needs an extra is
#: listed here, with it.
EXTRAS: dict[str, str] = {}

PUBLIC_STABILITY = (
    "Public: follows [semantic versioning](../guarantees.md#stability). Below 1.0, a minor "
    "release may change it, and the CHANGELOG says how."
)
CORE_STABILITY = (
    "Returned, not exported: its fields are the Panel Core format's, and change only as "
    "[the format](../../panel_core.md) says, under `CORE_FORMAT_VERSION`."
)


@dataclass(frozen=True)
class Group:
    """One group of `__all__`, as its comment names it, and the names under it."""

    title: str
    names: tuple[str, ...]


@dataclass(frozen=True)
class Page:
    """A generated page: its file's stem, its title, and the names it documents."""

    stem: str
    title: str
    names: tuple[str, ...]
    intro: str = ""


def groups() -> list[Group]:
    """`scenet.__all__`, cut where its comments cut it: `# -- compiling ----`."""
    tree = ast.parse(INIT.read_text(encoding="utf-8"))
    lines = INIT.read_text(encoding="utf-8").splitlines()
    node = next(
        node
        for node in tree.body
        if isinstance(node, ast.Assign)
        and any(getattr(target, "id", None) == "__all__" for target in node.targets)
    )
    found: list[Group] = []
    title = ""
    names: list[str] = []
    if not isinstance(node.value, ast.List):
        raise TypeError("scenet.__all__ is not a list literal")
    for element in node.value.elts:
        if not (isinstance(element, ast.Constant) and isinstance(element.value, str)):
            raise TypeError(f"scenet.__all__ holds {ast.unparse(element)}, not a name")
        # The comment above an element, if any, opens a new group.
        for line in lines[(element.lineno - 2) : element.lineno - 1]:
            match = re.match(r"\s*# -- (.+?) -+\s*$", line)
            if match:
                if names:
                    found.append(Group(title, tuple(names)))
                title, names = match.group(1), []
        names.append(element.value)
    found.append(Group(title, tuple(names)))
    return found


def _title(group: str) -> str:
    return group[:1].upper() + group[1:]


def since() -> dict[str, str]:
    """The minor version each public name appeared in, as `since.toml` records it."""
    return tomllib.loads(SINCE.read_text(encoding="utf-8"))["since"]


def parameters_since() -> dict[str, str]:
    """`function.parameter` to the minor version the parameter was added in."""
    return tomllib.loads(SINCE.read_text(encoding="utf-8")).get("parameters", {})


def _is_grouped(obj: object) -> bool:
    """Whether a name shares a page: an enumeration, an error, or a value."""
    if inspect.isclass(obj):
        return issubclass(obj, enum.Enum | BaseException)
    return not callable(obj)


def pages() -> list[Page]:
    """Every generated page, in the order of `__all__`."""
    found: list[Page] = []
    for group in groups():
        own = [name for name in group.names if not _is_grouped(getattr(scenet, name))]
        shared = [name for name in group.names if _is_grouped(getattr(scenet, name))]
        found.extend(Page(name, f"`{name}`", (name,)) for name in own)
        if shared:
            if group.title == "errors":
                found.append(Page("errors", "Errors", tuple(shared), ERRORS_INTRO))
            elif group.title == "metadata":
                found.append(Page("version", "The version", tuple(shared)))
            else:
                stem = re.sub(r"\W+", "-", group.title).strip("-") + "-values"
                found.append(
                    Page(stem, f"{_title(group.title)}: the values", tuple(shared), VALUES_INTRO)
                )
    found.append(Page("core-types", "The Panel Core types", core_types(), CORE_INTRO))
    return found


ERRORS_INTRO = (
    "Every error a public function raises is one of these, and a "
    "{py:exc}`~scenet.errors.ScenetError`: `except ScenetError` catches them all. Each also "
    "keeps the built-in exception it would have been, so `except ValueError` keeps working. "
    "See {py:mod}`scenet.errors` for what the promise covers."
)
VALUES_INTRO = "The enumerations and values of this group, each the word an author writes."
CORE_INTRO = (
    "The types a compile returns, read off `result.core` and `book.pages`. They are not in "
    "`scenet.__all__`: import one from `scenet.core` to annotate with it. What each field "
    "means is in [the Panel Core reference](../../panel_core.md)."
)


def core_types() -> tuple[str, ...]:
    """Every class `scenet.core` defines for a Core but the two tiers, which have pages."""
    return tuple(
        name
        for name in scenet.core.__all__
        if inspect.isclass(getattr(scenet.core, name))
        and getattr(scenet.core, name).__module__ == "scenet.core"
        and name not in scenet.__all__
        and name not in {"CoreModel", "Speaking"}
    )


def documented_publicly() -> list[str]:
    """The full name of every object a generated page documents.

    `docs/conf.py` leaves each of them off the module pages, the internals, so that no
    object is described twice.
    """
    return [
        _full_name(name, getattr(scenet, name) if name in scenet.__all__ else None)
        for page in pages()
        for name in page.names
    ]


def _object(name: str) -> object:
    return getattr(scenet, name) if name in scenet.__all__ else getattr(scenet.core, name)


def _module(name: str) -> str:
    if name == "__version__":
        return "scenet"
    if name == "PLACES":
        return "scenet.places"
    return _object(name).__module__  # type: ignore[attr-defined]


def _full_name(name: str, obj: object | None = None) -> str:
    return f"{_module(name)}.{name}"


def _directive(name: str) -> str:
    obj = _object(name)
    if inspect.isclass(obj):
        return "autoexception" if issubclass(obj, BaseException) else "autoclass"
    if callable(obj):
        return "autofunction"
    return "autodata"


def card(name: str) -> str:
    """The header card of one name: a two-column table, as Qt's and cppreference's are."""
    module = _module(name)
    public = name in scenet.__all__
    source = f"{SOURCE}{module.replace('.', '/')}"
    source += "/__init__.py" if module == "scenet" else ".py"
    extra = EXTRAS.get(name)
    rows = [
        ("Import", f"`from {'scenet' if public else module} import {name}`"),
        # The package itself has no module page: its public names are its pages.
        ("Defined in", f"{_module_link(module)} ([source]({source}))"),
    ]
    if public:
        install = f"`pip install 'scenet[{extra}]'`" if extra else "`pip install scenet`"
        rows += [
            ("Install", install),
            ("Since", since()[name]),
            ("Stability", PUBLIC_STABILITY),
        ]
    else:
        rows.append(("Stability", CORE_STABILITY))
    body = "\n".join(f"| {key} | {value} |" for key, value in rows)
    return f"| | |\n|---|---|\n{body}\n"


def _module_link(module: str) -> str:
    return f"`{module}`" if module == "scenet" else f"{{py:mod}}`{module}`"


def _autodoc(name: str) -> str:
    lines = [f".. {_directive(name)}:: {_full_name(name)}"]
    if _directive(name) == "autodata":
        lines.append("   :no-value:")
    added = parameters_since()
    for parameter, version in sorted(added.items(), key=lambda item: (_version(item[1]), item[0])):
        function, _, argument = parameter.partition(".")
        if function == name:
            lines += [
                "",
                f"   .. versionadded:: {version}",
                f"      The ``{argument}`` parameter.",
            ]
    return "```{eval-rst}\n" + "\n".join(lines) + "\n```\n"


def page(spec: Page) -> str:
    """One page's Markdown."""
    parts = [f"# {spec.title}\n"]
    if spec.intro:
        parts.append(spec.intro + "\n")
    single = len(spec.names) == 1
    for name in spec.names:
        if not single:
            parts.append(f"## `{name}`\n")
        parts.append(card(name))
        parts.append(_autodoc(name))
    return "\n".join(parts)


def at_a_glance() -> str:
    """The index's overview: every public name, by group, linked to its entry."""
    by_name = {name: spec for spec in pages() for name in spec.names}
    rows = []
    for group in groups():
        links = " · ".join(_link(name, by_name[name]) for name in group.names)
        rows.append(f"| **{_title(group.title)}** | {links} |")
    toctree = "\n".join(f"public/{spec.stem}" for spec in pages())
    return (
        f"{BEGIN}\n\n"
        "| | Names |\n|---|---|\n" + "\n".join(rows) + "\n\n"
        "```{toctree}\n:hidden:\n:caption: Public names\n\n" + toctree + "\n```\n\n"
        f"{END}"
    )


def _link(name: str, spec: Page) -> str:
    return f"[`{name}`](public/{spec.stem}.md)"


def index() -> str:
    """`index.md`, with its generated block rewritten."""
    text = INDEX.read_text(encoding="utf-8")
    before, _, rest = text.partition(BEGIN)
    _, _, after = rest.partition(END)
    if not rest:
        raise SystemExit(f"{INDEX.relative_to(ROOT)} has no {BEGIN!r}")
    return before + at_a_glance() + after


def committed_files() -> dict[Path, bytes]:
    """Every generated file, with the content it should have."""
    files = {PUBLIC / f"{spec.stem}.md": page(spec).encode("utf-8") for spec in pages()}
    files[INDEX] = index().encode("utf-8")
    return files


def _stale() -> list[Path]:
    expected = committed_files()
    stale = [p for p, data in expected.items() if not p.exists() or p.read_bytes() != data]
    if PUBLIC.exists():
        stale += [p for p in sorted(PUBLIC.rglob("*")) if p.is_file() and p not in expected]
    return stale


# ---------------------------------------------------------------- mining the tags


def _git(*arguments: str) -> str:
    """What `git` prints, run in the repository. Only `--mine-since` needs it."""
    git = shutil.which("git")
    if git is None:
        raise SystemExit("--mine-since reads the release tags, and needs git")
    return subprocess.run(  # noqa: S603 -- git, with arguments this script spells
        [git, *arguments], capture_output=True, text=True, encoding="utf-8", check=True, cwd=ROOT
    ).stdout


def _tags() -> list[str]:
    listed = _git("tag", "--list", "v*").split()
    return sorted(listed, key=lambda tag: tuple(int(part) for part in tag[1:].split(".")))


def _show(tag: str, path: str) -> str:
    return _git("show", f"{tag}:{path}")


def _exported(source: str) -> list[str]:
    for node in ast.parse(source).body:
        if isinstance(node, ast.Assign | ast.AnnAssign):
            target = node.targets[0] if isinstance(node, ast.Assign) else node.target
            if getattr(target, "id", None) == "__all__" and node.value is not None:
                return list(ast.literal_eval(node.value))
    return []


@functools.cache
def _definitions(tag: str) -> dict[str, list[str]]:
    """Each module-level function in the package at a tag, with its parameters."""
    files = _git("ls-tree", "-r", "--name-only", tag, "src/scenet").split()
    found: dict[str, list[str]] = {}
    for path in files:
        if not path.endswith(".py"):
            continue
        for node in ast.parse(_show(tag, path)).body:
            if isinstance(node, ast.FunctionDef):
                arguments = node.args
                every = [*arguments.posonlyargs, *arguments.args, *arguments.kwonlyargs]
                found.setdefault(node.name, [argument.arg for argument in every])
    return found


def mine() -> str:
    """`since.toml`, from `__all__` and each public function's parameters at every tag."""
    minor = {tag: ".".join(tag[1:].split(".")[:2]) for tag in _tags()}
    first: dict[str, str] = {}
    for tag, version in minor.items():
        for name in _exported(_show(tag, "src/scenet/__init__.py")):
            first.setdefault(name, version)
    current = scenet.__version__.split(".")
    upcoming = f"{current[0]}.{int(current[1]) + 1}"
    names = {name: first.get(name, upcoming) for name in scenet.__all__}
    added: dict[str, str] = {}
    for name in scenet.__all__:
        obj = getattr(scenet, name)
        if not inspect.isfunction(obj):
            continue
        known: set[str] | None = None
        for tag, version in minor.items():
            if _version(version) < _version(names[name]):
                continue
            listed = _definitions(tag).get(name)
            if listed is None:
                continue
            if known is None:
                known = set(listed)
                continue
            for parameter in listed:
                if parameter not in known:
                    added.setdefault(f"{name}.{parameter}", version)
            known |= set(listed)
        for parameter in inspect.signature(obj).parameters:
            if known is not None and parameter not in known:
                added.setdefault(f"{name}.{parameter}", upcoming)
    lines = [SINCE_HEADER, "[since]"]
    lines += [f"{_key(name)} = {names[name]!r}".replace("'", '"') for name in sorted(names)]
    lines += ["", "[parameters]"]
    lines += [f'"{key}" = "{added[key]}"' for key in sorted(added)]
    return "\n".join(lines) + "\n"


def _version(minor: str) -> tuple[int, ...]:
    return tuple(int(part) for part in minor.split("."))


def _key(name: str) -> str:
    return name if re.fullmatch(r"[A-Za-z0-9_-]+", name) else f'"{name}"'


SINCE_HEADER = """\
# The minor release each public name first appeared in: the first release tag whose
# `scenet.__all__` lists it. A name added since the last release takes the next minor
# version. `[parameters]` is each parameter a public function gained after it was public.
#
# Mined from the tags by `uv run python scripts/build_api_pages.py --mine-since`, and
# not from the CHANGELOG, whose first mention of a name is often later than its release.
"""


def main() -> int:
    """Rewrite the pages, or with `--check` report whether any is stale."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report stale pages instead")
    parser.add_argument(
        "--mine-since", action="store_true", help="rewrite since.toml from the release tags"
    )
    args = parser.parse_args()
    if args.mine_since:
        SINCE.write_text(mine(), encoding="utf-8", newline="\n")
        print(f"wrote {SINCE.relative_to(ROOT)}")
        return 0
    stale = _stale()
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0
    expected = committed_files()
    for path in stale:
        if path in expected:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected[path])
            print(f"wrote {path.relative_to(ROOT)}")
        else:
            path.unlink()
            print(f"removed {path.relative_to(ROOT)}")
    if not stale:
        print("everything is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
