"""Every diagnostic has an entry, and every entry's documents do what it says (#320).

When `scenet check` or the compiler says something, the reader looks it up in
`docs/reference/diagnostics.md`, as in Rust's error index: what it means, why it happens,
how to fix it, and a document that gives it beside the same document fixed. The page is
generated by `scripts/build_diagnostics.py` from the catalogue and `tests/rule_corpus/`;
these tests fail on a rule or a compile note without an entry, an entry whose document does
not give its diagnostic, a fixed twin that still gives something, and a page that is stale.
"""

import importlib.util
import re
import sys
from pathlib import Path
from types import ModuleType
from typing import Any, get_args

import pytest
import yaml

from scenet.diagnostics import COMPILE_NOTES, RULES
from scenet.pipeline import CompileNoteRule
from tests import myst
from tests.doc_examples import fences

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / "docs" / "reference"
PAGE = REFERENCE / "diagnostics.md"
MANIFEST = ROOT / "examples" / "gallery" / "manifest.yaml"


def _load(name: str) -> ModuleType:
    """Import a script from `scripts/`, which is not a package."""
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / f"{name}.py")
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


build = _load("build_diagnostics")
language = build.language()
IDS: list[str] = build.ids()
#: Every id an entry shows a document for: all but `internal`, which no document gives on
#: purpose, since it is what a bug is reported as.
SHOWN = [name for name in IDS if name != "internal"]
DOCUMENTS = sorted(path for path in build.CORPUS.iterdir() if path.is_file())
TWINS = sorted(path for path in build.FIXED.iterdir() if path.is_file())


def _entry(name: str) -> str:
    """An entry's own text: from its heading to the next."""
    text = PAGE.read_text(encoding="utf-8")
    for section in myst.sections(text):
        if section.heading.anchor == name:
            return section.text
    raise AssertionError(f"no entry for {name}")


def _row(name: str, row: str) -> str:
    found = re.search(rf"^\| {row} \| (.*) \|$", _entry(name), re.MULTILINE)
    assert found, f"{name} has no {row} row"
    return found.group(1)


class TestEveryDiagnosticHasAnEntry:
    def test_the_catalogue_is_every_rule_and_every_compile_note(self):
        assert sorted(build.catalogue()) == sorted({*RULES, *get_args(CompileNoteRule)})

    def test_every_compile_note_is_described(self):
        assert sorted(COMPILE_NOTES) == sorted(get_args(CompileNoteRule))
        for name, note in COMPILE_NOTES.items():
            assert note.level == "note", name
            assert note.summary, name
            assert note.description, name
            assert note.help, name

    @pytest.mark.parametrize("name", IDS)
    def test_it_has_an_entry(self, name: str):
        assert name in myst.anchors(PAGE), f"no `### `{name}`` on {PAGE.name}"

    def test_every_entry_is_for_a_diagnostic_there_is(self):
        headings = myst.headings(PAGE.read_text(encoding="utf-8"))
        entries = [heading.anchor for heading in headings if heading.level == 3]
        assert entries == IDS

    def test_the_page_matches_a_fresh_build(self):
        assert not build.stale(), "run `uv run python scripts/build_diagnostics.py`"

    def test_generation_is_deterministic(self):
        assert build.page() == build.page()

    def test_it_is_in_the_reference(self):
        index = (REFERENCE / "index.md").read_text(encoding="utf-8")
        assert re.search(r"^diagnostics$", index, re.MULTILINE)
        assert "(diagnostics.md)" in index


class TestEveryEntryShowsItsFault:
    @pytest.mark.parametrize("name", SHOWN)
    def test_it_has_a_document_and_its_fixed_twin(self, name: str):
        paths = build.documents(name)
        assert paths, f"add tests/rule_corpus/{name}.panel.yaml, a document that gives it"
        for path in paths:
            assert build.fixed(path).is_file(), f"add {build.fixed(path).relative_to(ROOT)}"

    def test_internal_has_none_and_says_why(self):
        assert build.documents("internal") == []
        assert "No document gives it on purpose" in _entry("internal")

    def test_every_document_is_for_a_diagnostic(self):
        assert sorted({path.name.split(".")[0] for path in DOCUMENTS} - set(IDS)) == []

    def test_every_twin_has_its_document(self):
        assert [twin.name for twin in TWINS if not (build.CORPUS / twin.name).is_file()] == []

    @pytest.mark.parametrize("path", DOCUMENTS, ids=lambda path: path.name)
    def test_a_document_gives_exactly_its_diagnostic(self, path: Path):
        assert build.told(path) == [path.name.split(".")[0]], build.said(path)

    @pytest.mark.parametrize("path", TWINS, ids=lambda path: path.name)
    def test_its_fixed_twin_gives_nothing(self, path: Path):
        assert build.told(path) == [], build.said(path)

    @pytest.mark.parametrize("path", DOCUMENTS + TWINS, ids=lambda path: path.as_posix())
    def test_it_opens_on_a_line_saying_what_is_wrong_or_what_changed(self, path: Path):
        lines = path.read_text(encoding="utf-8").splitlines()
        first = lines[1] if path.suffix == ".script" else lines[0]
        assert first.startswith("# "), f"{path.name}: open on a `# ` comment"

    @pytest.mark.parametrize("name", SHOWN)
    def test_the_entry_shows_each_pair_in_order(self, name: str):
        """The document, what the command line says of it, then the fixed twin."""
        shown = [
            (dict(fence.options).get("gives"), fence.text)
            for fence in fences(PAGE)
            if fence.directive == "scenet-example"
            and fence.text in {p.read_text(encoding="utf-8") for p in self._pair_paths(name)}
        ]
        expected = [
            (gives, path.read_text(encoding="utf-8"))
            for document in build.documents(name)
            for gives, path in ((name, document), (None, build.fixed(document)))
        ]
        assert shown == expected

    @pytest.mark.parametrize("name", SHOWN)
    def test_the_entry_says_what_the_command_line_prints(self, name: str):
        entry = _entry(name)
        for path in build.documents(name):
            assert f"`{build.command(name, path)}` says:" in entry
            printed = "\n".join(build.said(path))
            assert f"```text\n{printed}\n```" in entry
            # A rule's id is in what `scenet check` prints. `scenet build` prints a compile
            # note's sentence alone, which this entry shows, so a search for it lands here.
            assert name in printed or name in COMPILE_NOTES

    @staticmethod
    def _pair_paths(name: str) -> list[Path]:
        return [p for d in build.documents(name) for p in (d, build.fixed(d))]


class TestEveryEntrySaysWhatItIs:
    @pytest.mark.parametrize("name", IDS)
    def test_its_level_and_what_it_says(self, name: str):
        rule = build.catalogue()[name]
        assert _row(name, "Level") == rule.level
        assert _row(name, "Says") == rule.summary

    @pytest.mark.parametrize("name", IDS)
    def test_why_and_how_to_fix_it(self, name: str):
        rule = build.catalogue()[name]
        entry = _entry(name)
        assert f"**Why it happens.** {rule.description}" in entry
        assert f"**How to fix it.** {rule.help}" in entry

    @pytest.mark.parametrize("name", IDS)
    def test_since(self, name: str):
        """A diagnostic added since the last release takes the next minor version."""
        version = build.since().get(name)
        assert version is not None, f"add {name!r} to docs/reference/diagnostics.since.toml"
        assert re.fullmatch(r"\d+\.\d+", version)
        assert _row(name, "Since") == version

    def test_since_names_only_diagnostics_there_are(self):
        assert sorted(set(build.since()) - set(IDS)) == []

    def test_the_glance_table_lists_every_entry(self):
        text = PAGE.read_text(encoding="utf-8")
        listed = re.findall(r"^\| \[`([a-z-]+)`\]\(#([a-z-]+)\) \| (\w+) \|", text, re.MULTILINE)
        assert [name for name, _, _ in listed] == IDS
        assert all(name == anchor for name, anchor, _ in listed)


class TestKeysAndEntriesLinkEachOther:
    """A key card links each diagnostic it can give; each entry links back to its keys."""

    CARDS: dict[str, Any] = language.cards()

    @pytest.mark.parametrize("name", sorted(CARDS))
    def test_a_card_links_the_entry_of_each_diagnostic_it_gives(self, name: str):
        card = self.CARDS[name]
        row = language.facts(card).split("| Diagnostics | ", 1)[1].split(" |\n", 1)[0]
        linked = re.findall(r"\[`([a-z-]+)`\]\(\.\./diagnostics\.md#([a-z-]+)\)", row)
        assert linked, f"{name}: its diagnostics are not linked"
        assert [rule for rule, anchor in linked if rule != anchor] == []
        assert [rule for rule, _ in linked] == language.diagnostics_of(card)
        assert re.sub(r"\[`[a-z-]+`\]\([^)]+\)(, )?", "", row) == ""

    def test_every_diagnostic_a_card_names_has_an_entry(self):
        named = {rule for card in self.CARDS.values() for rule in language.diagnostics_of(card)}
        assert sorted(named - set(IDS)) == []

    def test_every_diagnostic_but_a_documents_is_given_by_a_key(self):
        named = {rule for card in self.CARDS.values() for rule in language.diagnostics_of(card)}
        assert sorted(set(IDS) - language.DOCUMENT_RULES - named) == []

    @pytest.mark.parametrize("name", IDS)
    def test_an_entry_links_each_key_that_gives_it(self, name: str):
        row = _row(name, "Keys")
        if name in language.DOCUMENT_RULES:
            assert row.startswith("None:")
            return
        linked = re.findall(r"\(language/([\w-]+)\.md(?:#([\w-]*))?\)", row)
        assert linked, f"{name} links no key"
        for page, anchor in linked:
            target = REFERENCE / "language" / f"{page}.md"
            assert target.is_file(), page
            if anchor:
                assert anchor in myst.anchors(target), f"{page}.md#{anchor}"
        if name in ("invalid-field", "puppet-file", "artwork-contract"):
            return
        giving = {
            f"{card.page}.md#{card.anchor}"
            for card in self.CARDS.values()
            if name in language.diagnostics_of(card)
        }
        assert {f"{page}.md#{anchor}" for page, anchor in linked} >= giving


class TestTheGalleryAndTheEntries:
    CARDS: dict[str, Any] = language.cards()
    ENTRIES: list[dict[str, Any]] = yaml.safe_load(MANIFEST.read_text(encoding="utf-8"))["examples"]

    def test_an_example_read_about_here_lands_on_an_entry(self):
        named = [
            entry["doc"]
            for entry in self.ENTRIES
            if entry["doc"].startswith("reference/diagnostics.md")
        ]
        assert named
        anchors = myst.anchors(PAGE)
        assert [doc for doc in named if doc.partition("#")[2] not in anchors] == []

    def test_an_example_that_shows_a_note_reads_about_it(self):
        """The "What Scenet tells you" examples each show a note. "Read about it" opens its
        entry, or the card of the key the example is about, which links the entry."""
        told = [entry for entry in self.ENTRIES if entry.get("group") == "What Scenet tells you"]
        assert told
        cards = {f"reference/language/{c.page}.md#{c.anchor}": c for c in self.CARDS.values()}
        for entry in told:
            doc, notes = entry["doc"], entry["notes"]
            if doc in cards:
                assert set(notes) & set(language.diagnostics_of(cards[doc])), entry["file"]
            else:
                assert doc in {f"reference/diagnostics.md#{note}" for note in notes}, entry["file"]

    @pytest.mark.parametrize("name", IDS)
    def test_an_entry_names_the_examples_that_show_it(self, name: str):
        showing = [entry["title"] for entry in self.ENTRIES if name in entry.get("notes", [])]
        if not showing:
            assert "| In the gallery |" not in _entry(name)
            return
        row = _row(name, "In the gallery")
        assert re.findall(r"\[([^\]]+)\]\(\.\./gallery\.md#[\w-]+\)", row) == showing
