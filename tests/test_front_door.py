def _toctrees(text: str) -> list[list[str]]:
    blocks = re.findall(r"```\{toctree\}\n(.*?)```", text, re.DOTALL)
    return [
        [line.strip() for line in block.splitlines() if line.strip() and not line.startswith(":")]
        for block in blocks
    ]


