def _version(text: str) -> tuple[int, int]:
    major, minor = text.split(".")[:2]
    return int(major), int(minor)


def _name(version: tuple[int, int]) -> str:
    return f"{version[0]}.{version[1]}"


def _releases() -> list[tuple[int, int]]:
    return [_version(v) for v in re.findall(r"^## \[(\d+\.\d+)\.\d+\]", _read(CHANGELOG), re.M)]


def _latest_release() -> tuple[int, int]:
    return max(_releases())


def _toml(path: str) -> dict[str, Any]:
    return tomllib.loads(_read(DOCS / path))


def _since_of_option(option: str) -> str:
    return _toml("reference/cli.since.toml")["options"][option]


def _since_of(evidence: str) -> str:
    """The release a name appeared in, read from the files mined from the tags."""
    cli = _toml("reference/cli.since.toml")
    language = _toml("reference/language/since.toml")
    api = _toml("reference/api/since.toml")["since"]
    if evidence.startswith("scenet "):
        command = evidence.removeprefix("scenet ")
        return cli["options"][command] if " " in command else cli["commands"][command]
    if evidence.endswith("()"):
        return api[evidence.removesuffix("()")]
    if evidence in api:
        return api[evidence]
    if ": " in evidence:
        key, _, value = evidence.partition(": ")
        return language["values"].get(f"{key}={value}") or language["keys"][key]
    return language["keys"][evidence]


#: The matrix's parts, in order; the roadmap follows them.
AREAS = ("Frontends", "Layout", "Lettering", "Outputs", "Tools")


def _rows() -> list[tuple[str, str, list[str], str]]:
    rows: list[tuple[str, str, list[str], str]] = []
    for section in sections(_read(STATUS)):
        if section.heading.text not in AREAS:
            continue
        for line in section.text.splitlines():
            cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
            if not line.startswith("|") or len(cells) != 3 or set(cells[2]) <= set("-"):
                continue
            if cells == ["Feature", "Written as", "Since"]:
                continue
            rows.append(
                (section.heading.text, cells[0], re.findall(r"`([^`]+)`", cells[1]), cells[2])
            )
    return rows


ROWS = _rows()


class TestWhatScenetDoesToday:
    def test_its_title(self):
        assert headings(_read(STATUS))[0].text == "What Scenet does today"

    def test_its_parts_then_the_roadmap(self):
        titles = [heading.text for heading in headings(_read(STATUS)) if heading.level == 2]
        assert titles == [*AREAS, "Roadmap"]

    def test_it_is_no_longer_a_log_of_phases(self):
        text = _read(STATUS)
        assert "Phase" not in text
        assert "phase" not in text
        assert "Single panels compile end to end" not in text

    def test_every_part_has_rows(self):
        assert {area for area, *_ in ROWS} == set(AREAS)

    @pytest.mark.parametrize(
        ("area", "feature", "evidence", "since"), ROWS, ids=[row[1] for row in ROWS]
    )
    def test_each_since_is_true(self, area: str, feature: str, evidence: list[str], since: str):
        """The earliest release of what it is written as, and a release the CHANGELOG has."""
        match = re.fullmatch(r"(\d+\.\d+)(, not yet released)?", since)
        assert match, f"{feature}: {since!r} is 'X.Y' or 'X.Y, not yet released'"
        version = _version(match.group(1))
        if evidence:
            assert version == min(_version(_since_of(name)) for name in evidence)
        if version > _latest_release():
            assert match.group(2), f"{feature} is not in {_name(_latest_release())}: say so"
            assert version == (_latest_release()[0], _latest_release()[1] + 1)
        else:
            assert not match.group(2)
            assert version in _releases(), f"the CHANGELOG has no {_name(version)}"

    def test_unreleased_work_is_in_the_changelog(self):
        unreleased = _read(CHANGELOG).split("## [Unreleased]", 1)[1].split("\n## [", 1)[0]
        assert unreleased.strip()

    def test_the_specification_disclaimer_is_gone(self):
        for path in [
            *DOCS.rglob("*.md"),
            *ROOT.glob("skills/**/*.md"),
            ROOT / "src" / "scenet" / "scenet-spec.md",
        ]:
            if "_build" not in path.parts:
                assert "not a report of what is implemented" not in _read(path), path


