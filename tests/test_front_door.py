def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def _flat(text: str) -> str:
    """Prose with its Markdown emphasis and line breaks taken out."""
    return re.sub(r"\s+", " ", re.sub(r"[*_]", "", text)).strip()


def _sentence(text: str) -> str:
    """The opening sentence: the paragraph that starts "Scenet compiles"."""
    match = re.search(r"^Scenet compiles .*?(?:\n\n|\Z)", text, re.MULTILINE | re.DOTALL)
    assert match, "the page says what Scenet does in a sentence that starts 'Scenet compiles'"
    return _flat(match.group(0))


def _umbrella() -> dict[str, Any]:
    return yaml.safe_load(_read(UMBRELLA))


def _umbrella_source() -> str:
    """The gallery document, without the comment that introduces it there."""
    lines = _read(UMBRELLA).splitlines(keepends=True)
    while lines and (lines[0].startswith("#") or not lines[0].strip()):
        lines.pop(0)
    return "".join(lines)


