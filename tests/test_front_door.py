def _is_umbrella(document: object) -> bool:
    """Alice and Bob, and nobody else, trading the umbrella panel's two lines."""
    if not isinstance(document, dict) or "panels" in document or "pages" in document:
        return False
    lines = [
        event.get("say", {}).get("text")
        for event in document.get("script") or []
        if isinstance(event, dict)
    ]
    cast = document.get("cast")
    return (
        lines == ["You forgot your umbrella!", "I know."]
        and isinstance(cast, dict)
        and set(cast) == {"alice", "bob"}
    )


def _umbrella_blocks() -> list[tuple[str, dict[str, Any]]]:
    found: list[tuple[str, dict[str, Any]]] = []
    for block in document_blocks():
        if block.kind != "panel":
            continue
        try:
            document = yaml.safe_load(block.fence.text)
        except yaml.YAMLError:
            continue  # a document broken on purpose, to show its diagnostic
        if _is_umbrella(document):
            found.append((block.fence.where, document))
    for fence in fences(ROOT / "skills" / "scenet" / "SKILL.md"):
        if fence.language == "yaml" and _is_umbrella(yaml.safe_load(fence.text)):
            found.append((fence.where, yaml.safe_load(fence.text)))
    for path in sorted(ROOT.glob("examples/**/*.yaml")):
        document = yaml.safe_load(_read(path))
        if _is_umbrella(document):
            found.append((path.relative_to(ROOT).as_posix(), document))
    return found


