#: Markdown links and images, inline and by reference, and HTML attributes.
_TARGETS = (
    re.compile(r"\]\(\s*<?([^)\s>]+)"),
    re.compile(r"^\s*\[[^\]]+\]:\s*<?(\S+?)>?\s*$", re.MULTILINE),
    re.compile(r"""\b(?:href|src)\s*=\s*["']([^"']+)"""),
)


def _link_targets(text: str) -> list[str]:
    outside_code = re.sub(r"```.*?```", "", text, flags=re.DOTALL)
    return [target for pattern in _TARGETS for target in pattern.findall(outside_code)]


